from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Any, ClassVar

import numpy as np


# TODO: make this class as independent of the use case as possible
@dataclass
class Input:
    """
    A velocity command: forward (vx), lateral (vy) and yaw rate (w), each in [-1, 1]
    """

    vx: float = 0.0
    vy: float = 0.0
    w: float = 0.0

    @property
    def as_array(self) -> np.ndarray:
        return np.array([self.vx, self.vy, self.w])

    def update(
        self, vx: float | None = None, vy: float | None = None, w: float | None = None
    ) -> None:
        """Overwrite all or some fields."""
        if vx is not None:
            self.vx = vx
        if vy is not None:
            self.vy = vy
        if w is not None:
            self.w = w


@dataclass
class DeviceConfig:
    """The parameters of a command device: the base of every device's nested ``Params``.

    In a run config they are the values under ``command: <name>:``. ``name`` and the device
    built by ``make()`` come from the device class the ``Params`` belong to.
    """

    name: ClassVar[str] = ""
    device_class: ClassVar[type["Device"]]

    def make(self) -> "Device":
        return self.device_class(self)


class Device(ABC):
    """A source of velocity commands. Subclasses set ``name`` (the key under ``command:`` in
    a run config) and define a nested ``Params(DeviceConfig)`` dataclass."""

    name: ClassVar[str] = ""

    @dataclass
    class Params(DeviceConfig):
        """No parameters by default."""

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        if "Params" in vars(cls):  # link the parameters to their device
            cls.Params.name = cls.name
            cls.Params.device_class = cls

    @abstractmethod
    def update(self) -> None:
        """
        Update the state of the (software) device, by refreshing the internally held input values
        """

    @abstractmethod
    def read(self) -> Input:
        """
        Read (return) the input generated by device
        """

    @abstractmethod
    def reset(self) -> None:
        """
        Reset the device to its initial state. Called when resetting the environment
        """
